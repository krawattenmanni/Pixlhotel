export function getEquippedBadges(
  player: Pick<PlayerState, 'equippedBadges' | 'equippedBadgeId' | 'unlockedBadges'>
): string[] {
  if (Array.isArray(player.equippedBadges) && player.equippedBadges.length > 0) {
    return player.equippedBadges.slice(0, 5);
  }
  const set: string[] = [];
  if (player.equippedBadgeId) set.push(player.equippedBadgeId);
  for (const b of player.unlockedBadges) {
    if (set.length >= 5) break;
    if (!set.includes(b)) set.push(b);
  }
  return set;
}
